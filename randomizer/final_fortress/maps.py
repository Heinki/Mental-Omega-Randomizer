"""Map selection and deterministic, read-only skirmish conversion."""

from copy import deepcopy
import hashlib
from pathlib import Path

from randomizer.maps.ini import IniLines, section_value_map, merge_ini_section_values


def map_definitions(config):
    return [entry for entry in (config['map'], *config.get('additional_maps', [])) if entry is not None]


def select_map(config, map_id):
    """Produce a complete balance snapshot with the selected map as its default."""
    selected = next((entry for entry in map_definitions(config) if entry['id'] == map_id), None)
    if selected is None:
        raise ValueError('Unknown Final Fortress map: ' + str(map_id))
    snapshot = deepcopy(config)
    snapshot['map'] = deepcopy(selected)
    # Frozen runs need only their own map, including when replayed by guests.
    snapshot.pop('additional_maps', None)
    return snapshot


def source_lines(game_root, definition):
    """Convert only generated bytes; preserve installed terrain and scenery."""
    root = Path(game_root).resolve()
    source = (root / definition['source']).resolve()
    if not source.is_relative_to(root):
        raise ValueError('Final Fortress map must be inside the game directory.')
    lines = IniLines(source.read_text(encoding='latin-1').splitlines())
    if definition.get('clear_source_scripts') or definition.get('remove_source_units'):
        # Skirmish ambience uses the same limited local-variable namespace as
        # survival. Remove its complete trigger graph, including object tags.
        removed = ({'triggers', 'events', 'actions', 'tags', 'celltags', 'variablenames', 'digest'}
                   if definition.get('clear_source_scripts') else set())
        excluded = set(definition.get('remove_source_units', []))
        retained = []
        section = ''
        tag_fields = {'structures': 6, 'units': 7, 'infantry': 8, 'aircraft': 7}
        for line in lines:
            if line.strip().startswith('[') and line.strip().endswith(']'):
                section = line.strip()[1:-1].lower()
            if section in removed:
                continue
            if section in tag_fields and '=' in line and not line.lstrip().startswith(';'):
                key, value = line.split('=', 1)
                fields = value.split(',')
                if section in ('units', 'infantry', 'aircraft') and fields[1] in excluded:
                    continue
                if definition.get('clear_source_scripts'):
                    fields[tag_fields[section]] = 'None'
                line = key + '=' + ','.join(fields)
            retained.append(line)
        lines = IniLines(retained)
    merge_ini_section_values(lines, {'Waypoints': {
        key: str(p['y'] * 1000 + p['x']) for key, p in definition.get('start_positions', {}).items()}})
    return lines


def inspect_map(game_root, definition):
    """Check source suitability without extracting or rewriting campaign maps."""
    if definition is None:
        raise ValueError('No Final Fortress map is configured.')
    root = Path(game_root).resolve()
    source = (root / definition['source']).resolve()
    if not source.is_relative_to(root):
        raise ValueError('Final Fortress map must be inside the game directory.')
    data = source.read_bytes()
    lines = source_lines(game_root, definition)
    basic = section_value_map(lines, 'Basic')
    if basic.get('multiplayeronly') not in {'1', 'yes', 'true'}:
        raise ValueError('Final Fortress requires a multiplayer skirmish map.')
    actors = [definition['player_waypoint'], *definition['enemy_waypoints'],
              *definition.get('allied_waypoints', [])]
    if int(basic.get('maxplayer', '0')) < len(actors):
        raise ValueError('Final Fortress requires enough spawn positions for enemies and configured helpers.')
    if basic.get('ignoreglobalaitriggers', 'no').lower() not in {'0', 'no', 'false'}:
        raise ValueError('This map disables normal skirmish AI triggers.')
    points = section_value_map(lines, 'Waypoints')
    positions = []
    for waypoint in actors:
        value = points.get(str(waypoint), '')
        if not value.isdigit():
            raise ValueError(f'Missing or invalid source waypoint {waypoint}.')
        cell = int(value)
        positions.append({'waypoint': waypoint, 'x': cell % 1000, 'y': cell // 1000})
    size = section_value_map(lines, 'Map').get('size', '').split(',')
    if len(size) != 4 or any(not part.strip().isdigit() for part in size):
        raise ValueError('Invalid skirmish map dimensions.')
    return {
        'source': str(source), 'sha256': hashlib.sha256(data).hexdigest(),
        'width': int(size[2]), 'height': int(size[3]), 'positions': positions,
    }
